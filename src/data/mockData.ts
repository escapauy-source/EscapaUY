export const getActivityById = (id: string): Activity | undefined => {
  return activities.find(a => a.id === id);
};

export const getActivitiesByHotel = (hotelId: string): Activity[] => {
  const hotel = getHotelById(hotelId);
  if (!hotel) return activities;

  // Obtener ciudades cercanas a la ciudad del hotel
  const nearestCities = citiesProximity[hotel.city] || [hotel.city];

  // Filtrar actividades por proximidad, priorizando la misma ciudad
  const sameCity = activities.filter(a => a.city === hotel.city);
  const nearby = activities.filter(
    a => a.city !== hotel.city && nearestCities.includes(a.city)
  );
  const others = activities.filter(
    a => !nearestCities.includes(a.city)
  );

  return [...sameCity, ...nearby, ...others];
};

